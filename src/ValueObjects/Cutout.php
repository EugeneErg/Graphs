<?php

declare(strict_types=1);

namespace EugeneErg\Graphs\ValueObjects;

/**
 * Кусок графа вместе с его экземплярами.
 *
 * Сам по себе `Piece` — это просто вершины и рёбра. Здесь к ним добавлено то,
 * что делает кусок узнаваемым на картинке: за каждой его вершиной и каждым его
 * ребром закреплён экземпляр, и закреплён раз и навсегда. Пока кусок не
 * отрезан, его экземпляры лежат поверх родительских и неотличимы от них;
 * в момент разреза они отъезжают — и видно, что отделился именно этот кусок,
 * а не появился новый.
 *
 * То, что у родителя после разреза не осталось, кусок забирает вместе с
 * экземпляром: вершина не раздваивается зря, а просто уезжает с куском.
 */
final readonly class Cutout
{
    /**
     * @param ?int $parent из какого куска вырезан; null — исходный граф
     * @param array<int, string> $vertexes вершина => ключ её экземпляра
     * @param array<string, string> $edges имя ребра => ключ его экземпляра
     */
    public function __construct(
        public Piece $piece,
        public ?int $parent,
        public array $vertexes,
        public array $edges,
    ) {
    }
}
