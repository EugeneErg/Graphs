<?php

declare(strict_types=1);

namespace EugeneErg\Graphs\ValueObjects;

/**
 * Что именно произошло на шаге алгоритма.
 *
 * По виду шага отрисовка решает, как его показать: подсветить, развезти
 * куски по сторонам, вырезать ветви с дублями общих вершин или собрать всё
 * обратно.
 */
enum StageKind: string
{
    /** Исходный граф. */
    case Graph = 'graph';

    /** Одна волна заливки: что закрасилось на этом шаге. */
    case Fill = 'fill';

    /** Граф распался на несвязные куски. */
    case Components = 'components';

    /** Найдены точки сочленения. */
    case ArticulationVertexes = 'articulation';

    /** Кусок разрезан на двусвязные ветви. */
    case Branches = 'branches';

    /** Из ветви вырезано очередное поле. */
    case Field = 'field';

    /** В ветвях найдены грани плоской укладки. */
    case Faces = 'faces';

    /** Выбрана внешняя грань. */
    case OuterFace = 'outer';

    /** Определён порядок, в котором поля лягут на картинку. */
    case Order = 'order';

    /** Очередное поле добавлено в строящуюся укладку. */
    case Build = 'build';

    /** Вершины поехали: расслабление. */
    case Relax = 'relax';

    /**
     * На шаге вершины меняют положение, поэтому отрисовка привязывает к нему
     * кадры укладки, а не одну неподвижную картинку.
     */
    public function isMoving(): bool
    {
        return $this === self::Relax;
    }
}
